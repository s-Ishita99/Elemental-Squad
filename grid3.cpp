
#include "grid3.h"

Grid3::Grid3()
{
    createMap();
}

void Grid3::createMap()
{
    string rocky[5][7] =
    {
        {".", ".", "B", ".", ".", "CW", "#"},
        {"B", "B", ".", "B", ".", ".", "#"},
        {".", ".", "B", "CW", ".", ".", "E"},
        {"H", ".", ".", ".", ".", ".", "#"},
        {"#", "#", "#", "#", "#", "#", "#"}
    };

    string sprinty[5][7] =
    {
        {"#", "#", "#", "#", "#", "#", "#"},
        {"#", "#", "#", ".", ".", "BO", "#"},
        {".", "BO", ".", ".", "SW", ".", "#"},
        {"BO", "SW", "BO", ".", ".", ".", "#"},
        {"#", ".", "E", "#", "#", "#", "#"}
    };

    string splash[5][7] =
    {
        {"#", "#", "#", "#", "#", "0", "#"},
        {"#", "K", "#", ".", ".", ".", "#"},
        {"0", ".", "0", ".", "0", ".", "#"},
        {"E", ".", ".", ".", "0", ".", "."},
        {"#", "#", "0", "#", "#", "#", "#"}
    };

    string blaze[5][7] =
    {
        {"#", "#", ".", "#", "#", "#", "#"},
        {"#", "C#", ".", ".", ".", "P", "#"},
        {"#", ".", ".", "C#", ".", "#", "#"},
        {"E", "T", ".", ".", "C#", ".", "#"},
        {"#", "#", "#", "#", "#", "#", "#"}
    };

    for (int r = 0; r < 5; r++)
    {
        for (int c = 0; c < 7; c++)
        {
            tiles[r][c] = rocky[r][c];
            tiles[r][c + 7] = sprinty[r][c];

            tiles[r + 5][c] = splash[r][c];
            tiles[r + 5][c + 7] = blaze[r][c];
        }
    }

    // Character positions are drawn separately.
    tiles[0][0] = ".";
    tiles[2][7] = ".";
    tiles[5][9] = ".";
    tiles[8][6] = ".";
}
